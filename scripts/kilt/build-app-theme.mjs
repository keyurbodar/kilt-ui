// Builds registry/kilt/app/theme.css: the Tailwind theme Kiki's app layer is
// styled against, re-pointed at Kilt's CDS tokens. Names the site (FF) or
// Tailwind already own are set only inside `.kilt-app`, so the vendored
// components restyle there and nowhere else.
import { readFileSync, writeFileSync } from "node:fs";

const at = (p) => new URL(p, import.meta.url).pathname;
const read = (p) => readFileSync(at(p), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const RENAME = { bg: "background", fg: "foreground", text: "foreground", "primary-text": "primary-foreground", "destructive-text": "destructive-foreground" };

/** Top-level blocks as [prelude, body]; bodies keep their nested braces. */
function blocks(css) {
  const out = [];
  let depth = 0, start = 0, prelude = "";
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") { if (depth++ === 0) { prelude = css.slice(start, i).trim(); start = i + 1; } }
    else if (css[i] === "}" && --depth === 0) { out.push([prelude.split(";").pop().trim(), css.slice(start, i)]); start = i + 1; }
  }
  return out;
}
const decls = (body) =>
  [...body.matchAll(/(--[\w-]+(?:\*)?)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]);

const themeNames = (css) => new Set(blocks(css).filter(([p]) => p.startsWith("@theme")).flatMap(([, b]) => decls(b).map(([n]) => n)));
const owned = new Set([
  ...themeNames(readFileSync(at("../../app/globals.css"), "utf8")),
  ...themeNames(readFileSync(at("../../node_modules/tailwindcss/theme.css"), "utf8")),
]);
const kiltTokens = new Set(readFileSync(at("../../registry/kilt/tokens.css"), "utf8").match(/--kilt-[\w-]+/g));

const theme = { static: [], inline: [] };
const scoped = [];
const extra = [];
const media = [];
for (const file of ["primitives", "semantic", "components", "motion", "utilities"]) {
  for (const [prelude, body] of blocks(read(`./vendor/kiki-tokens/${file}.css`))) {
    if (prelude.startsWith("@theme")) {
      const mode = prelude.includes("inline") ? "inline" : "static";
      for (const [name, value] of decls(body)) {
        if (name.endsWith("*")) continue;
        (owned.has(name) ? scoped : theme[mode]).push(`  ${name}: ${value};`);
      }
    } else if (/^:root\b/.test(prelude)) {
      // The raw layer the @theme names read (--responsive-icon-sm, ...).
      for (const [name, value] of decls(body)) scoped.push(`  ${name}: ${value};`);
    } else if (prelude.startsWith("@media")) {
      const inner = blocks(body).filter(([p]) => /^:root\b/.test(p)).flatMap(([, b]) => decls(b));
      if (inner.length) media.push(`${prelude} {\n  .kilt-app {\n${inner.map(([n, v]) => `    ${n}: ${v};`).join("\n")}\n  }\n}`);
    } else if (prelude.startsWith("@utility") || prelude.startsWith("@keyframes")) {
      extra.push(`${prelude} {${body}}`);
    }
  }
}

const themeVars = [...new Set(read("./vendor/default.css").match(/^\s+--[\w-]+(?=:)/gm).map((s) => s.trim().slice(2)))];
const bridge = themeVars.flatMap((v) => {
  const target = v.startsWith("sh-") ? `--kilt-${v}` : `--kilt-color-${RENAME[v] ?? v}`;
  return kiltTokens.has(target) ? [`  --${v}: var(${target});`] : [];
});

const css = `/* Generated by scripts/kilt/build-app-theme.mjs from Kiki's token layer. Do not edit. */
@theme static {
${theme.static.join("\n")}
}

@theme inline {
${theme.inline.join("\n")}
}

/* Inside .kilt-app, Kiki's theme variables read Kilt's CDS tokens, and the
   Tailwind names the site already owns take Kiki's values. */
.kilt-app {
${bridge.join("\n")}
${scoped.join("\n")}
}

${media.join("\n\n")}

${extra.join("\n\n")}
`;
writeFileSync(at("../../registry/kilt/app/theme.css"), css);
console.log(`kilt app theme: ${theme.static.length + theme.inline.length} new theme vars, ${scoped.length} scoped, ${bridge.length} bridged to kilt tokens, ${extra.length} utilities/keyframes`);
