#!/usr/bin/env node
// Compiles the CDS export in cds/ (pulled from the Doop canvas) into kilt's
// source: typed tokens, one stylesheet per component, and the doc catalog.
// Re-run after refreshing cds/; every output is overwritten.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join, basename } from "node:path";

const ROOT = new URL("../..", import.meta.url).pathname;
const CDS = join(ROOT, "cds");
const OUT = join(ROOT, "registry/kilt");
const PREFIX = "kilt";
const HEADER = (src) =>
  `/* Generated by scripts/kilt/build-cds.mjs from ${src}. Do not edit. */\n`;

// ---------------------------------------------------------------- tokens

function parseDecls(body) {
  const map = new Map();
  for (const m of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);?/g)) map.set(m[1], m[2].trim());
  return map;
}

function parseRules(css) {
  return [...css.matchAll(/([^{}]+)\{([^}]*)\}/g)].map((m) => ({
    selector: m[1].trim(),
    decls: parseDecls(m[2]),
  }));
}

const canvasRules = parseRules(readFileSync(join(CDS, "tokens.css"), "utf8"));
const themeOf = (sel) => (sel.includes('"light"') ? "light" : sel.includes('"touch"') ? "touch" : "dark");
const canvas = Object.fromEntries(canvasRules.map((r) => [themeOf(r.selector), r.decls]));

// The foundations guide carries the values Doop has no token type for
// (elevation, motion, z-index, blur) as a fenced CSS block.
const guide = readFileSync(join(CDS, "guidelines.md"), "utf8");
const guideCss = guide.match(/```css\n([\s\S]*?)```/)[1].replace(/\/\*[\s\S]*?\*\//g, "");
const guideRules = parseRules(guideCss.replace(/@media[^{]+\{[^{}]*\{[^}]*\}\s*\}/g, ""));
const guideDark = guideRules.find((r) => r.selector === ":root").decls;
const guideLight = guideRules.find((r) => r.selector.includes('"light"')).decls;

const GROUPS = [
  ["color", /^color-/, "<color>"],
  ["radius", /^radius-/, "<length>"],
  ["spacing", /^spacing/, "<length>"],
  ["container", /^container-/, "<length>"],
  ["breakpoint", /^breakpoint-/, "<length>"],
  ["font-family", /^font-(sans|mono|terminal)$/, "*"],
  ["font-weight", /^font-weight-/, "<number>"],
  ["font-size", /^text-/, "<length>"],
  ["line-height", /^leading-/, "<number>"],
  ["letter-spacing", /^tracking-/, "<length>"],
  ["elevation", /^sh-/, "*"],
  ["duration", /^duration-/, "<time>"],
  ["easing", /^(ease-|default-transition)/, "*"],
  ["z-index", /^z-/, "<integer>"],
  ["blur", /^blur-/, "<length>"],
];
const groupOf = (name) => GROUPS.find(([, re]) => re.test(name)) ?? ["misc", /./, "*"];

const dark = new Map([...canvas.dark, ...guideDark]);
const light = new Map([...canvas.light, ...guideLight]);
const touch = canvas.touch;
const names = [...dark.keys()];
const v = (n) => `--${PREFIX}-${n}`;
// Bare zeros ("0em") need a unit for a registered <length>; Doop already
// writes units everywhere else.
const initial = (n, syntax) => {
  const val = dark.get(n);
  if (syntax === "<color>" && /light-dark|var\(|lab\(/.test(val)) return null;
  return val;
};

let tokensCss = HEADER("cds/tokens.css + cds/guidelines.md") +
  `/* kilt tokens: every CDS value, typed with @property.
   Themes: dark is the default; .light / [data-theme="light"] or the OS
   preference switches colours (light-dark()), [data-density="touch"]
   switches to the touch size ladder. */\n\n`;

for (const n of names) {
  const [, , syntax] = groupOf(n);
  if (syntax === "*") continue;
  const init = initial(n, syntax);
  if (init == null) continue;
  tokensCss += `@property ${v(n)} { syntax: "${syntax}"; inherits: true; initial-value: ${init}; }\n`;
}

const colorOf = (n) => {
  const d = dark.get(n), l = light.get(n) ?? d;
  return d === l ? d : `light-dark(${l}, ${d})`;
};

tokensCss += `\n:root,\n.light,\n.dark,\n[data-theme] {\n`;
let lastGroup = "";
for (const n of names) {
  const [group] = groupOf(n);
  if (group !== lastGroup) tokensCss += `\n  /* ${group} */\n`;
  lastGroup = group;
  const val = group === "color" ? colorOf(n) : dark.get(n);
  tokensCss += `  ${v(n)}: ${val};\n`;
}
tokensCss += `}\n\n/* No theme class: follow the OS. */\n:root:not(.light, .dark, [data-theme]) {\n  color-scheme: light dark;\n}\n\n.dark,\n[data-theme="dark"] {\n  color-scheme: dark;\n}\n\n.light,\n[data-theme="light"] {\n  color-scheme: light;\n}\n\n`;

// Shadows can't ride light-dark(); they switch with the theme selector.
const lightOnly = names.filter((n) => groupOf(n)[0] !== "color" && light.has(n) && light.get(n) !== dark.get(n));
const lightBlock = lightOnly.map((n) => `  ${v(n)}: ${light.get(n)};`).join("\n");
const darkBlock = lightOnly.map((n) => `  ${v(n)}: ${dark.get(n)};`).join("\n");
tokensCss += `@media (prefers-color-scheme: light) {\n  :root:not(.dark):not([data-theme="dark"]) {\n${lightBlock.replace(/^/gm, "  ")}\n  }\n}\n\n.dark,\n[data-theme="dark"] {\n${darkBlock}\n}\n\n.light,\n[data-theme="light"] {\n${lightBlock}\n}\n\n`;

const touchOnly = names.filter((n) => groupOf(n)[0] !== "color" && touch.has(n) && touch.get(n) !== dark.get(n));
tokensCss += `[data-density="touch"] {\n${touchOnly.map((n) => `  ${v(n)}: ${touch.get(n)};`).join("\n")}\n}\n\n`;
tokensCss += `@media (prefers-reduced-motion: reduce) {\n  [class*="kilt-"],\n  [class*="kilt-"] * {\n    animation-duration: 1ms !important;\n    transition-duration: 1ms !important;\n  }\n}\n`;

mkdirSync(join(OUT, "styles"), { recursive: true });
// Motion values cds/guidelines.md states in prose ("Motion" section), promoted to tokens.
const MOTION = [
  ["duration-exit", "<time>", "120ms", "Overlay exit"],
  ["duration-tooltip-exit", "<time>", "110ms", "Tooltip exit"],
  ["delay-hover", "<time>", "350ms", "Tooltip and preview card open delay"],
  ["scale-overlay-from", "<number>", "0.97", "Menu, popover, preview card enter/exit scale"],
  ["scale-dialog-from", "<number>", "0.95", "Dialog and command palette enter scale"],
  ["scale-toast-from", "<number>", "0.8", "Toast enter scale"],
  ["shift-pane-from", "<length>", "4px", "Right pane enter offset"],
];
tokensCss += `\n/* motion (cds/guidelines.md) */\n`;
for (const [n, syntax, val] of MOTION) tokensCss += `@property ${v(n)} { syntax: "${syntax}"; inherits: true; initial-value: ${val}; }\n`;
tokensCss += `:root {\n${MOTION.map(([n, , val, note]) => `  ${v(n)}: ${val}; /* ${note} */`).join("\n")}\n}\n`;

writeFileSync(join(OUT, "tokens.css"), tokensCss.replace(/var\(--(?!kilt-)/g, "var(--kilt-"));

const tokensTs =
  `// Generated by scripts/kilt/build-cds.mjs. Do not edit.\n\n` +
  `export const kiltTokens = {\n${names
    .map((n) => `  ${JSON.stringify(n)}: { group: ${JSON.stringify(groupOf(n)[0])}, cssVar: "${v(n)}", dark: ${JSON.stringify(dark.get(n))}, light: ${JSON.stringify(light.get(n) ?? dark.get(n))}, touch: ${JSON.stringify(touch.get(n) ?? dark.get(n))} },`)
    .join("\n")}\n} as const;\n\n` +
  `export type KiltTokenName = keyof typeof kiltTokens;\n` +
  `export type KiltTokenGroup = (typeof kiltTokens)[KiltTokenName]["group"];\n\n` +
  `/** Prose motion values from cds/guidelines.md; \`ms\` fields feed JS delay props. */\n` +
  `export const kiltMotion = {\n${MOTION.map(([n, , val]) => `  ${JSON.stringify(n)}: { cssVar: "${v(n)}", value: ${JSON.stringify(val)}${val.endsWith("ms") ? `, ms: ${parseFloat(val)}` : ""} },`).join("\n")}\n} as const;\n\n` +
  `/** \`var(--kilt-…)\` for a token, typed so a typo fails the build. */\n` +
  `export const token = (name: KiltTokenName) => \`var(\${kiltTokens[name].cssVar})\` as const;\n`;
writeFileSync(join(OUT, "tokens.ts"), tokensTs);

// ------------------------------------------------------------ components

const components = readdirSync(join(CDS, "components"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => ({ slug: basename(f, ".json"), ...JSON.parse(readFileSync(join(CDS, "components", f), "utf8")) }));

const classesIn = (html) => new Set([...html.matchAll(/class="([^"]+)"/g)].flatMap((m) => m[1].split(/\s+/)));
const rootClass = (html) => html.match(/class="([^"\s]+)/)?.[1];
const roots = new Map(components.map((c) => [rootClass(c.template), c.slug]));
const tokenSet = new Set(names);

// Specimen states (data-state="…") also match the live attribute Base UI or
// the platform sets, so the same rule styles a specimen and a real control.
const LIVE_STATE = {
  disabled: ":disabled, [data-disabled], [aria-disabled=\"true\"]",
  focus: ":focus-visible",
  selected: "[data-selected], [aria-selected=\"true\"], [aria-current=\"page\"], [data-pressed]",
  open: "[data-popup-open], [data-open], [aria-expanded=\"true\"]",
  invalid: "[aria-invalid=\"true\"], [data-invalid]",
  indeterminate: "[data-indeterminate]",
  checked: "[data-checked]",
  highlighted: "[data-highlighted]",
};

export function compileComponentCss(c) {
  const own = classesIn(c.template);
  const root = rootClass(c.template);
  const mapClass = (cls) => {
    if (cls === root) return `${PREFIX}-${c.slug}`;
    if (own.has(cls)) return `${PREFIX}-${c.slug}__${cls}`;
    if (roots.has(cls)) return `${PREFIX}-${roots.get(cls)}`;
    return `${PREFIX}-${c.slug}__${cls}`;
  };
  let css = c.css;
  // Elevation copies Doop inlines per component live in tokens.css.
  css = css.replace(/--sh-[a-z-]+:[^;}]*;?/g, "");
  css = css.replace(/[^{}]+\{\s*\}\n?/g, "");
  css = css.replace(/\[data-doop-theme="light"\]/g, ':is(.light, [data-theme="light"])');
  css = css.replace(/\[data-doop-theme="touch"\]/g, '[data-density="touch"]');
  css = css.replace(/\[data-state="([a-z-]+)"\]/g, (m, s) => (LIVE_STATE[s] ? `:is(${m}, ${LIVE_STATE[s]})` : m));
  css = css.replace(/\[data-checked="true"\]/g, "[data-checked]");
  css = css.replace(/\[data-disabled="true"\]/g, ":is([data-disabled], :disabled)");
  css = css.replace(/\[data-focus="true"\]/g, ':is([data-focus="true"], :focus-visible, :has(:focus-visible))');
  css = css.replace(/--([a-z0-9-]+)/g, (m, n) => (tokenSet.has(n) ? v(n) : m));
  // Class selectors only: skip numbers like ".5px" and keyframe percents.
  css = css.replace(/(?<!\d)\.([a-zA-Z_][\w-]*)/g, (m, cls) => `.${mapClass(cls)}`);
  css = css.replace(/@keyframes\s+([\w-]+)/g, (m, k) => `@keyframes ${PREFIX}-${k}`);
  for (const k of [...c.css.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]))
    css = css.replace(new RegExp(`(animation[^;]*?)\\b${k}\\b`, "g"), `$1${PREFIX}-${k}`);
  css = css.replace(/(\.kilt-(input|textarea))((?:\[[^\]]*\])*)\s\.kilt-\2__(ph|tx)\s*\{([^}]*)\}/g, (m, r, _s, pre, _c, body) =>
    `${m}\n${r}${pre ?? ""}::placeholder {${body}}`);
  return css.replace(/\}\s*/g, "}\n");
}

for (const c of components) {
  writeFileSync(join(OUT, "styles", `${c.slug}.css`), HEADER(`cds/components/${c.slug}.json`) + compileComponentCss(c));
}

const catalog = components.map((c) => ({
  slug: c.slug,
  name: c.name,
  description: c.description,
  signature: c.signature,
  props: (c.props ?? []).map(({ name, type, default: def, options, description }) => ({ name, type, default: def, options, description })),
}));
mkdirSync(join(ROOT, "lib/kilt"), { recursive: true });
writeFileSync(
  join(ROOT, "lib/kilt/catalog.gen.ts"),
  `// Generated by scripts/kilt/build-cds.mjs from cds/components. Do not edit.\n\n` +
    `export interface KiltProp { name: string; type: string; default?: string; options?: string[]; description?: string }\n` +
    `export interface KiltCatalogEntry { slug: string; name: string; description: string; signature: string; props: KiltProp[] }\n\n` +
    `export const kiltCatalog: KiltCatalogEntry[] = ${JSON.stringify(catalog, null, 2)};\n`,
);

console.log(`kilt: ${names.length} tokens, ${components.length} component stylesheets`);

// ----------------------------------------------------------------- icons
// Every glyph in a CDS template, keyed by the class of the element that
// holds it, so components draw Capy's exact SVGs.

const pascal = (s) => s.replace(/(^|[-_\s])(\w)/g, (_, __, ch) => ch.toUpperCase()).replace(/[^\w]/g, "");
const jsxAttrs = (svg) =>
  svg
    .replace(/ data-doop-[a-z-]+="[^"]*"/g, "")
    .replace(/ (stroke|fill|clip|stop|font|text)-([a-z]+)=/g, (_, a, b) => ` ${a}${b[0].toUpperCase()}${b.slice(1)}=`)
    .replace(/ class="[^"]*"/g, "")
    .replace(/ style="[^"]*"/g, "");
const icons = new Map();
const seen = new Map();
for (const c of components) {
  const seenHolders = new Map();
  for (const m of c.template.matchAll(/<(span|button|div|kbd)[^>]*?class="([^"]+)"[^>]*>\s*(<svg[\s\S]*?<\/svg>)(\s*<svg[\s\S]*?<\/svg>)?/g)) {
    for (const svg of [m[3], m[4]].filter(Boolean)) {
    const ownClass = svg.match(/^\s*<svg[^>]*class="([^"]+)"/)?.[1];
    let holder = ownClass ?? m[2].split(/\s+/).filter((k) => !k.startsWith("si") || k.includes("-")).pop();
    const n = (seenHolders.get(holder) ?? 0) + 1;
    seenHolders.set(holder, n);
    if (n > 1) holder += n;
    m[3] = svg.trim();
    const body = jsxAttrs(m[3]).replace(/^<svg([^>]*)>/, (_, a) => `<svg${a.replace(/ aria-hidden="true"/, "")} aria-hidden="true" {...props}>`);
    const name = `${pascal(c.slug)}${pascal(holder)}Icon`;
    if (icons.has(name)) continue;
    const dup = seen.get(body);
    icons.set(name, dup ? { alias: dup } : { body });
    if (!dup) seen.set(body, name);
    }
  }
}
writeFileSync(
  join(OUT, "icons.tsx"),
  `// Generated by scripts/kilt/build-cds.mjs from cds/components. Do not edit.\nimport type { SVGProps } from "react";\n\ntype IconProps = SVGProps<SVGSVGElement>;\n\n` +
    [...icons]
      .map(([name, i]) => (i.alias ? `export const ${name} = ${i.alias};` : `export function ${name}(props: IconProps) {\n  return (\n    ${i.body}\n  );\n}`))
      .join("\n\n") + "\n",
);
console.log(`kilt: ${icons.size} icons`);

// ----------------------------------------------------------------- registry
// One shadcn item per component, deps read from each source's imports, so
// registry.json cannot drift from the code. Installs land in components/kilt/
// because sources import their siblings and stylesheets relatively.

const TARGET = "components/kilt";
const file = (path, type = "registry:file") => ({ path: `registry/kilt/${path}`, type, target: `${TARGET}/${path}` });
const sources = readdirSync(OUT).filter((f) => f.endsWith(".tsx") && !["icons.tsx", "icon.tsx"].includes(f)).map((f) => f.slice(0, -4));
const bySlug = new Map(components.map((c) => [c.slug, c]));

const kiltItems = [
  {
    name: "kilt-tokens",
    type: "registry:file",
    title: "Kilt Tokens",
    description: "Typed CDS tokens (@property), light/dark/touch themes, motion values and the live overlay layer every Kilt component imports.",
    files: [file("tokens.css"), file("tokens.ts"), file("styles/live.css")],
    categories: ["kilt"],
  },
  {
    name: "kilt-icons",
    type: "registry:file",
    title: "Kilt Icons",
    description: "The SVG glyphs drawn in the CDS component templates, as React components.",
    files: [file("icons.tsx")],
    categories: ["kilt"],
  },
];
kiltItems.push(
  {
    name: "kilt-themes",
    type: "registry:file",
    title: "Kilt Themes",
    description: "Capy's 13 colour presets and the Explore wallpaper themes as [data-color-theme] blocks over the kilt tokens.",
    registryDependencies: ["kilt-tokens"],
    files: [file("themes.css"), file("themes.ts")],
    categories: ["kilt"],
  },
  {
    name: "kilt-icon",
    type: "registry:ui",
    title: "Kilt Icon",
    description: "Capy's 350-glyph icon sprite on a 24px grid, rendered with <use>. Serve the sprite at /kilt/icons.svg.",
    registryDependencies: ["utils", "kilt-tokens"],
    files: [file("icon.tsx", "registry:ui"), file("icon-ids.ts"), { path: "public/kilt/icons.svg", type: "registry:file", target: "public/kilt/icons.svg" }],
    categories: ["kilt"],
  },
);
for (const slug of sources.sort()) {
  const src = readFileSync(join(OUT, `${slug}.tsx`), "utf8");
  const local = [...src.matchAll(/from "\.\/([\w-]+)"/g)].map((m) => m[1]);
  const styles = [...src.matchAll(/import "\.\/styles\/([\w-]+)\.css"/g)].map((m) => m[1]).filter((s) => s === slug);
  const ownCss = [...src.matchAll(/import "\.\/([\w-]+\.css)"/g)].map((m) => m[1]);
  const packages = [...new Set([...src.matchAll(/from "((?:@[\w-]+\/)?[\w-]+)[^"]*"/g)].map((m) => m[1]).filter((p) => !["react", "react-dom"].includes(p) && !p.startsWith("@/")))];
  const DESCRIPTIONS = { dither: "Capy's WebGL dither (Paper Shaders): procedural Dither, WallpaperBackdrop with grain/vignette, and the shared on-screen shader clock." };
  const c = bySlug.get(slug);
  kiltItems.push({
    name: `kilt-${slug}`,
    type: "registry:ui",
    title: `Kilt ${c?.name ?? pascal(slug)}`,
    description: c?.description ?? DESCRIPTIONS[slug] ?? "",
    ...(packages.length ? { dependencies: packages } : {}),
    registryDependencies: [
      "utils",
      ...new Set(local.filter((d) => d !== "icon-ids").map((d) => (d === "tokens" ? "kilt-tokens" : d === "icons" ? "kilt-icons" : `kilt-${d}`))),
      ...(local.includes("tokens") ? [] : ["kilt-tokens"]),
    ],
    files: [file(`${slug}.tsx`, "registry:ui"), ...styles.map((s) => file(`styles/${s}.css`)), ...ownCss.map((c) => file(c)), ...(ownCss.includes("effects.css") ? [file("textures/grain.svg")] : [])],
    categories: ["kilt"],
  });
}
kiltItems.push({
  name: "kilt",
  type: "registry:block",
  title: "Kilt",
  description: "Every Kilt component: the Capy Design System on Base UI.",
  registryDependencies: kiltItems.filter((i) => i.type === "registry:ui").map((i) => i.name),
  files: [],
  categories: ["kilt"],
});

const registryPath = join(ROOT, "registry.json");
const registry = JSON.parse(readFileSync(registryPath, "utf8"));
registry.items = [...registry.items.filter((i) => !i.name.startsWith("kilt")), ...kiltItems];
writeFileSync(registryPath, `${JSON.stringify(registry, null, 2)}\n`);
console.log(`kilt: ${kiltItems.length} registry items`);
